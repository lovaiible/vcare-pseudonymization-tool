// Setup only: runtime downloads are restricted to assets shipped with the app.
import { readFile, writeFile, mkdir, copyFile, readdir, rename, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createReadStream, createWriteStream } from 'node:fs';
import { Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../../', import.meta.url));
const manifest = JSON.parse(await readFile(path.join(root, 'browser/model-manifest.json')));
const verify = process.argv.includes('--verify');
async function hash(file) {
  const digest = createHash('sha256');
  for await (const chunk of createReadStream(file)) digest.update(chunk);
  return digest.digest('hex');
}
for (const item of manifest.files) {
  const dest = path.join(root, 'browser/public/models', manifest.revision, item.path);
  let valid = false;
  try { valid = await hash(dest) === item.sha256; } catch {}
  if (!valid) {
    if (verify) throw new Error('Model assets missing or changed. Run npm run setup.');
    console.log(`Downloading model asset: ${item.path}`);
    await mkdir(path.dirname(dest), { recursive: true });
    const response = await fetch(`https://huggingface.co/${manifest.model}/resolve/${manifest.revision}/${item.path}`);
    if (!response.ok || !response.body) throw new Error('Model download failed. Retry setup.');
    try {
      await pipeline(Readable.fromWeb(response.body), createWriteStream(dest + '.partial'));
      if (await hash(dest + '.partial') !== item.sha256) throw new Error('Model checksum mismatch.');
      await rename(dest + '.partial', dest);
    } finally { await rm(dest + '.partial', { force: true }); }
  }
}
// The npm lockfile pins runtime integrity. Runtime files live under a versioned URL.
const ort = JSON.parse(await readFile(path.join(root, 'node_modules/onnxruntime-web/package.json')));
const runtime = path.join(root, 'browser/public/runtime', ort.version);
const files = (await readdir(path.join(root, 'node_modules/onnxruntime-web/dist')))
  .filter(name => /^ort-wasm-simd-threaded\.(wasm|mjs)$/.test(name));
if (files.length !== 2) throw new Error('Expected WASM runtime files are unavailable.');
for (const name of files) {
  const source = path.join(root, 'node_modules/onnxruntime-web/dist', name);
  const dest = path.join(runtime, name);
  if (verify) {
    if (await hash(source) !== await hash(dest)) throw new Error('Runtime changed. Run npm run setup.');
  } else {
    await mkdir(runtime, { recursive: true });
    await copyFile(source, dest);
  }
}
if (!verify) {
  await writeFile(path.join(root, 'browser/src/runtime-version.js'), `// Generated by npm run setup from the locked runtime package.\nexport const runtimeVersion = ${JSON.stringify(ort.version)};\n`);
  const licences = path.join(root, 'browser/public/licences');
  await mkdir(licences, { recursive: true });
  for (const [name, source] of [['transformers.txt','@huggingface/transformers/LICENSE']]) {
    await copyFile(path.join(root, 'node_modules', source), path.join(licences, name));
  }
}

for (const name of ['favicon.png', ...((await readdir(path.join(root,'vcare_pseudonymizer/web/fonts'))).map(n=>'fonts/'+n))]) {
  const source=path.join(root,'vcare_pseudonymizer/web',name), dest=path.join(root,'browser/public',name);
  if(verify) { if(await hash(source)!==await hash(dest)) throw new Error('UI assets changed. Run npm run setup.'); }
  else { await mkdir(path.dirname(dest),{recursive:true}); await copyFile(source,dest); }
}
console.log('Model checksums and runtime assets verified.');
